function setLang(lang) {
	document.documentElement.lang = lang;
	localStorage.setItem('lang', lang);
	document.querySelectorAll('[data-i18n]').forEach(el => {
		const k = el.dataset.i18n;
		if (translations[lang][k]) el.textContent = translations[lang][k]
	});
	document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
		const k = el.dataset.i18nPlaceholder;
		if (translations[lang][k]) el.placeholder = translations[lang][k]
	});
	document.querySelectorAll('.lang-switch button').forEach(b => b.classList.toggle('active', b.dataset.lang === lang))
}
document.addEventListener('DOMContentLoaded', () => {
	setLang(localStorage.getItem('lang') || 'es');
	document.querySelectorAll('.lang-switch button').forEach(b => b.addEventListener('click', () => setLang(b.dataset.lang)));
	const nav = document.querySelector('.nav-toggle'),
		menu = document.querySelector('.nav-menu');
	if (nav && menu) nav.addEventListener('click', () => {
		menu.classList.toggle('open');
		nav.setAttribute('aria-expanded', menu.classList.contains('open'))
	});
	const search = document.querySelector('#service-search'),
		grid = document.querySelector('#service-grid'),
		empty = document.querySelector('.empty-state');
	if (search && grid) {
		search.addEventListener('input', () => {
			const q = search.value.toLowerCase().trim();
			let shown = 0;
			grid.querySelectorAll('.service').forEach(card => {
				const text = (card.innerText + ' ' + card.dataset.keywords).toLowerCase();
				const ok = text.includes(q);
				card.style.display = ok ? 'block' : 'none';
				if (ok) shown++
			});
			if (empty) empty.hidden = shown !== 0
		})
	}
});
